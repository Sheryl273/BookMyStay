/**
 * UseCase1HotelBookingApp
 * 
 * This class represents the entry point of the Hotel Booking application.
 * It demonstrates how a Java program starts execution using the main()
 * method and prints a welcome message to the console.
 *
 * 
 * @author Sheryl
 * @version 1.0
 */

public class UseCase1HotelBookingApp {

    /**
     * The main method is the entry point of the Java application.
     * The JVM calls this method to start program execution.
     * 
     * @param args Command-line arguments (not used in this program)
     */
    public static void main(String[] args) {

        // Print welcome message to the console
        System.out.println("Welcome to the Hotel Booking System");

        // Print application name and version
        System.out.println("Hotel Booking System v1.0");

        // Print startup confirmation
        System.out.println("Application started successfully!");

        // Program terminates after execution
    }
}